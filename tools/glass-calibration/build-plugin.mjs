// Writes figma-plugin/code.js from scenes.json, so the plugin and Drawpane's
// harness build the same cells. Run: node tools/glass-calibration/build-plugin.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
const scenes = JSON.parse(readFileSync(new URL("scenes.json", here), "utf8"));

const code = `// Generated by build-plugin.mjs from scenes.json: don't edit by hand.
// Builds a "Glass calibration" page of cells, each named glass-<id>.
const SCENES = ${JSON.stringify(scenes)};

function rgb(hex) {
  const n = (i) => parseInt(hex.slice(i, i + 2), 16) / 255;
  return { r: n(1), g: n(3), b: n(5) };
}

async function main() {
  const page = figma.createPage();
  page.name = "Glass calibration";
  await figma.setCurrentPageAsync(page);
  const { cell, backdrop, cells, defaults } = SCENES;
  cells.forEach((spec, i) => {
    const settings = { ...defaults, ...spec };
    const glassBox = { ...SCENES.glass, ...(spec.glass || {}) };
    const frame = figma.createFrame();
    frame.name = "glass-" + spec.id;
    frame.resize(cell.width, cell.height);
    frame.x = (i % cell.columns) * (cell.width + cell.gap);
    frame.y = Math.floor(i / cell.columns) * (cell.height + cell.gap);
    frame.clipsContent = true;
    frame.fills = [
      {
        type: "GRADIENT_LINEAR",
        gradientTransform: [
          [1, 0, 0],
          [0, 1, 0],
        ],
        gradientStops: backdrop.gradient.map((s) => ({
          position: s.position,
          color: { ...rgb(s.color), a: 1 },
        })),
      },
    ];
    for (let y = 0, k = 0; y < cell.height; y += backdrop.rows.every, k++) {
      const bar = figma.createRectangle();
      bar.resize(cell.width, backdrop.rows.height);
      bar.x = 0;
      bar.y = y;
      bar.fills = [
        {
          type: "SOLID",
          color: rgb(backdrop.rows.colors[k % backdrop.rows.colors.length]),
          opacity: backdrop.rows.opacity,
        },
      ];
      frame.appendChild(bar);
    }
    for (let x = 0; x < cell.width; x += backdrop.columns.every) {
      const bar = figma.createRectangle();
      bar.resize(backdrop.columns.width, cell.height);
      bar.x = x;
      bar.y = 0;
      bar.fills = [
        { type: "SOLID", color: rgb(backdrop.columns.color), opacity: backdrop.columns.opacity },
      ];
      frame.appendChild(bar);
    }
    const glass = spec.shape === "ellipse" ? figma.createEllipse() : figma.createRectangle();
    glass.name = "glass";
    glass.resize(glassBox.width, glassBox.height);
    glass.x = glassBox.x;
    glass.y = glassBox.y;
    if (spec.shape !== "ellipse") glass.cornerRadius = glassBox.cornerRadius;
    glass.fills = [{ type: "SOLID", color: { r: 1, g: 1, b: 1 }, opacity: 0 }];
    glass.effects = [
      {
        type: "GLASS",
        visible: true,
        lightIntensity: settings.lightIntensity,
        lightAngle: settings.lightAngle,
        refraction: settings.refraction,
        depth: Math.max(1, settings.depth),
        dispersion: settings.dispersion,
        radius: settings.frost,
      },
    ];
    frame.appendChild(glass);
  });
  figma.viewport.scrollAndZoomIntoView(page.children);
  figma.closePlugin("Made " + cells.length + " glass calibration cells.");
}

main().catch((error) => figma.closePlugin("Couldn't make the cells: " + error.message));
`;

const target = new URL("figma-plugin/code.js", here);
writeFileSync(target, code);
// Formatted like the rest of the repository, so lint passes on what's generated.
execFileSync("npx", ["biome", "format", "--write", target.pathname], { stdio: "ignore" });
console.log(`Wrote figma-plugin/code.js (${scenes.cells.length} cells).`);
