/**
 * The Drawpane release this installer carries: a built Worker, the web app's
 * assets, the D1 migrations and the Worker's configuration, all for one
 * version (see scripts/bundle-server.mjs). Installing copies it into the
 * instance's folder; upgrading replaces it.
 */
import { cp, readFile, rm, stat } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { InstanceConfig } from "./instance.js";

/** Where the release lives inside an instance's folder. */
export const SERVER_DIR = "server";

export interface Release {
  readonly version: string;
  /** The folder holding worker/, assets/, migrations/ and wrangler.template.json. */
  readonly root: string;
}

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The release bundled with this copy of the installer. */
export async function bundledRelease(): Promise<Release> {
  const pkg = JSON.parse(await readFile(join(packageRoot, "package.json"), "utf8")) as {
    version: string;
  };
  const root = join(packageRoot, SERVER_DIR);
  try {
    await stat(join(root, "wrangler.template.json"));
  } catch {
    throw new Error(
      "This installer has no server bundled. In the Drawpane repo, run `pnpm build` first.",
    );
  }
  return { version: pkg.version, root };
}

/** Puts the release into the instance's folder, replacing whatever release was there. */
export async function copyRelease(release: Release, dir: string): Promise<void> {
  const target = join(dir, SERVER_DIR);
  await rm(target, { recursive: true, force: true });
  await cp(release.root, target, { recursive: true });
}

/** The header that keeps people from editing the generated file. */
const HEADER = `// Generated by create-drawpane from drawpane.json: edit that instead, then run
// \`npm create drawpane@latest upgrade\` to apply it. Changes here are overwritten.
`;

/**
 * The instance's wrangler.jsonc: the release's Worker configuration (bindings,
 * Durable Object migrations, compatibility settings) with this instance's
 * names, ids and domain. Pure, so it can be tested without a release.
 */
export function renderWranglerConfig(
  template: Readonly<Record<string, unknown>>,
  config: InstanceConfig,
): string {
  const assets = (template.assets ?? {}) as Record<string, unknown>;
  const rendered: Record<string, unknown> = {
    ...template,
    name: config.name,
    // The Worker is already bundled: upload it as it is.
    main: `${SERVER_DIR}/worker/index.js`,
    no_bundle: true,
    upload_source_maps: true,
    workers_dev: config.domain === null,
    assets: { ...assets, directory: `${SERVER_DIR}/assets` },
    d1_databases: [
      {
        binding: "DB",
        database_name: config.database.name,
        // Wrangler needs an id to deploy; until the database exists, a placeholder keeps the file valid.
        database_id: config.database.id ?? "00000000-0000-0000-0000-000000000000",
        migrations_dir: `${SERVER_DIR}/migrations`,
      },
    ],
    r2_buckets: [{ binding: "FILES", bucket_name: config.bucket }],
    vars: { ...((template.vars ?? {}) as Record<string, string>), ...config.vars },
  };
  delete rendered.$schema;
  delete rendered.routes;
  if (config.domain) rendered.routes = [{ pattern: config.domain, custom_domain: true }];
  return `${HEADER}${JSON.stringify(rendered, null, 2)}\n`;
}

export async function readTemplate(release: Release): Promise<Record<string, unknown>> {
  return JSON.parse(await readFile(join(release.root, "wrangler.template.json"), "utf8")) as Record<
    string,
    unknown
  >;
}
