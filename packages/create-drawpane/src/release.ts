/**
 * The Drawpane release this installer carries: the two built Workers (the
 * main one and the agent runner), the web app's assets, the D1 migrations and
 * each Worker's configuration, all for one version (see
 * scripts/bundle-server.mjs). Installing copies it into the instance's
 * folder; upgrading replaces it.
 */
import { cp, readFile, rm, stat } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type InstanceConfig, instanceRunner } from "./instance.js";
import { Problem } from "./problem.js";

/** Where the release lives inside an instance's folder. */
export const SERVER_DIR = "server";

/** The release's configuration templates, one per Worker. */
export const MAIN_TEMPLATE = "wrangler.template.json";
export const RUNNER_TEMPLATE = "agent-runner.template.json";

/**
 * The rendered configurations in the instance's folder. The main Worker's
 * keeps the name Wrangler looks for by default, so `npx wrangler secret put`
 * and friends in the folder reach it, as the docs say. The runner's sits
 * beside it and is deployed with `wrangler deploy -c`. Both are in the
 * folder's root, so their relative paths (`server/...`) mean the same.
 */
export const MAIN_CONFIG = "wrangler.jsonc";
export const RUNNER_CONFIG = "agent-runner.wrangler.jsonc";

export interface Release {
  readonly version: string;
  /**
   * The folder holding worker/, agent-runner/, assets/, migrations/ and the
   * two templates (MAIN_TEMPLATE and RUNNER_TEMPLATE).
   */
  readonly root: string;
}

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The release bundled with this copy of the installer. */
export async function bundledRelease(): Promise<Release> {
  const pkg = JSON.parse(await readFile(join(packageRoot, "package.json"), "utf8")) as {
    version: string;
  };
  const root = join(packageRoot, SERVER_DIR);
  try {
    await stat(join(root, MAIN_TEMPLATE));
    await stat(join(root, RUNNER_TEMPLATE));
  } catch {
    throw new Problem(
      "This installer has no server bundled. In the Drawpane repo, run `pnpm build` first.",
    );
  }
  return { version: pkg.version, root };
}

/** Puts the release into the instance's folder, replacing whatever release was there. */
export async function copyRelease(release: Release, dir: string): Promise<void> {
  const target = join(dir, SERVER_DIR);
  await rm(target, { recursive: true, force: true });
  await cp(release.root, target, { recursive: true });
}

/** The header that keeps people from editing the generated file. */
const HEADER = `// Generated by create-drawpane from drawpane.json: edit that instead, then run
// \`npm create drawpane@latest upgrade\` to apply it. Changes here are overwritten.
`;

/** The vars both Workers get: the release's, the instance's over them, then the version. */
function renderVars(
  template: Readonly<Record<string, unknown>>,
  config: InstanceConfig,
  version: string,
  extra: Readonly<Record<string, string>> = {},
): Record<string, string> {
  return {
    ...((template.vars ?? {}) as Record<string, string>),
    ...config.vars,
    ...extra,
    // Last, so it always says what's really running.
    DRAWPANE_VERSION: version,
  };
}

/**
 * The D1 and R2 bindings: both Workers use the instance's database and bucket.
 * Migrations are applied through the main Worker's config only.
 */
function storage(config: InstanceConfig, { migrations }: { migrations: boolean }) {
  return {
    d1_databases: [
      {
        binding: "DB",
        database_name: config.database.name,
        // Wrangler needs an id to deploy; until the database exists, a placeholder keeps the file valid.
        database_id: config.database.id ?? "00000000-0000-0000-0000-000000000000",
        ...(migrations ? { migrations_dir: `${SERVER_DIR}/migrations` } : {}),
      },
    ],
    r2_buckets: [{ binding: "FILES", bucket_name: config.bucket }],
  };
}

interface DurableObjectBinding {
  readonly name: string;
  readonly class_name: string;
  readonly script_name?: string;
}

/**
 * The instance's wrangler.jsonc: the release's Worker configuration (bindings,
 * Durable Object migrations, compatibility settings) with this instance's
 * names, ids and domain. Pure, so it can be tested without a release.
 *
 * A Durable Object binding with a `script_name` binds the agent runner (the
 * release has no other script): it gets the instance's runner. On the Free
 * plan there's no runner, so those bindings and the CPU limit (Free refuses
 * it) are left out, and `AGENT_TOOLS: "off"` tells the Worker so.
 */
export function renderWranglerConfig(
  template: Readonly<Record<string, unknown>>,
  config: InstanceConfig,
  /** The release's version: the Worker reports it, and the health page offers newer ones. */
  version: string,
): string {
  const free = config.plan === "free";
  const assets = (template.assets ?? {}) as Record<string, unknown>;
  const rendered: Record<string, unknown> = {
    ...template,
    name: config.name,
    // The Worker is already bundled: upload it as it is.
    main: `${SERVER_DIR}/worker/index.js`,
    no_bundle: true,
    upload_source_maps: true,
    workers_dev: config.domain === null,
    assets: { ...assets, directory: `${SERVER_DIR}/assets` },
    ...storage(config, { migrations: true }),
    vars: renderVars(template, config, version, free ? { AGENT_TOOLS: "off" } : {}),
  };
  const durableObjects = template.durable_objects as
    | { bindings?: readonly DurableObjectBinding[] }
    | undefined;
  if (durableObjects?.bindings) {
    const runner = instanceRunner(config);
    rendered.durable_objects = {
      ...durableObjects,
      bindings: durableObjects.bindings
        .filter((b) => !(free && b.script_name))
        .map((b) => (b.script_name ? { ...b, script_name: runner } : b)),
    };
  }
  if (free) delete rendered.limits;
  delete rendered.$schema;
  delete rendered.routes;
  if (config.domain) rendered.routes = [{ pattern: config.domain, custom_domain: true }];
  delete rendered.send_email;
  if (config.sendEmail) rendered.send_email = [{ name: "EMAIL" }];
  return `${HEADER}${JSON.stringify(rendered, null, 2)}\n`;
}

/**
 * The agent runner's configuration (agent-runner.wrangler.jsonc): the
 * release's, with the instance's runner name, database and bucket. It has no
 * route and no workers.dev address: only the main Worker calls it. It gets
 * the instance's vars too, so settings like `GOOGLE_FONTS: "off"` reach it.
 */
export function renderRunnerConfig(
  template: Readonly<Record<string, unknown>>,
  config: InstanceConfig,
  version: string,
): string {
  const rendered: Record<string, unknown> = {
    ...template,
    name: instanceRunner(config),
    main: `${SERVER_DIR}/agent-runner/index.js`,
    no_bundle: true,
    upload_source_maps: true,
    workers_dev: false,
    ...storage(config, { migrations: false }),
    vars: renderVars(template, config, version),
  };
  delete rendered.$schema;
  delete rendered.routes;
  return `${HEADER}${JSON.stringify(rendered, null, 2)}\n`;
}

export async function readTemplate(
  release: Release,
  file: typeof MAIN_TEMPLATE | typeof RUNNER_TEMPLATE = MAIN_TEMPLATE,
): Promise<Record<string, unknown>> {
  return JSON.parse(await readFile(join(release.root, file), "utf8")) as Record<string, unknown>;
}
