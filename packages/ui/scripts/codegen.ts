// Helpers for emitting generated TypeScript that is already in the repo's Biome format, so
// `biome check` and the staleness tests agree with the generator byte for byte.

export type Data = string | number | boolean | readonly Data[] | { readonly [key: string]: Data };

export function tsKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function pad(indent: number): string {
  return " ".repeat(indent);
}

/** Biome prefers double quotes unless the string holds more double quotes than single ones. */
export function tsString(value: string): string {
  const doubles = value.split('"').length;
  const singles = value.split("'").length;
  if (doubles <= singles) return JSON.stringify(value);
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
}

function emitScalar(value: string | number | boolean): string {
  return typeof value === "string" ? tsString(value) : String(value);
}

/**
 * Emits `value` as a TypeScript expression starting at column `indent`. Objects and arrays are
 * always expanded one entry per line: Biome keeps an object expanded when its first key starts on
 * a new line, and an array that holds an expanded object breaks too.
 */
export function emit(value: Data, indent = 0): string {
  if (typeof value !== "object") return emitScalar(value);
  const inner = indent + 2;
  if (Array.isArray(value)) {
    const items: readonly Data[] = value;
    const lines = items.map((item) => `${pad(inner)}${emit(item, inner)},`);
    return `[\n${lines.join("\n")}\n${pad(indent)}]`;
  }
  const lines = Object.entries(value).map(
    ([key, item]) => `${pad(inner)}${tsKey(key)}: ${emit(item, inner)},`,
  );
  return `{\n${lines.join("\n")}\n${pad(indent)}}`;
}

