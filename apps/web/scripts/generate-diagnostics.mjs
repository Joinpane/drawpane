/**
 * Generates `apps/web/src/diagnostics/expected-pixels.ts` using the engine's CPU oracle
 * (`packages/engine/dist/worker`). Re-run whenever `DIAGNOSTIC_CELLS` changes:
 *
 *   node apps/web/scripts/generate-diagnostics.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import {
  CELL_CAMERA,
  CELL_HEIGHT,
  CELL_WIDTH,
  DIAGNOSTIC_CELLS,
} from "../src/diagnostics/scene.ts";

const workerDir = resolve(import.meta.dirname, "../../../packages/engine/dist/worker");
const glue = await import(pathToFileURL(resolve(workerDir, "engine.js")).href);
glue.initSync({ module: readFileSync(resolve(workerDir, "engine_bg.wasm")) });

const check = (label, o) => {
  const { ok, message } = o;
  o.free();
  if (!ok) throw new Error(`${label}: ${message}`);
};

const entries = {};

for (const cell of DIAGNOSTIC_CELLS) {
  const engine = new glue.Engine(0, 0);
  try {
    for (const img of cell.images ?? []) {
      check(`${cell.id} putImage`, engine.putImage(img.id, img.width, img.height, img.rgba, false));
    }
    check(`${cell.id} apply`, engine.apply(cell.build()));
    check(
      `${cell.id} pngBegin`,
      engine.pngBegin(
        CELL_WIDTH,
        CELL_HEIGHT,
        CELL_CAMERA.zoom,
        CELL_CAMERA.x,
        CELL_CAMERA.y,
        CELL_CAMERA.dpr,
        CELL_HEIGHT,
      ),
    );
    const chunks = [];
    const bandRows = engine.pngRows();
    for (let row = 0; row < CELL_HEIGHT; row += bandRows) {
      check(`${cell.id} pngBand`, engine.pngBand(new Float32Array(cell.background)));
      const body = engine.pngTake();
      if (body.length > 0) chunks.push(body);
    }
    const tail = engine.pngEnd();
    if (tail.length > 0) chunks.push(tail);
    entries[cell.id] = Buffer.concat(chunks).toString("base64");
  } finally {
    engine.pngAbort();
    engine.free();
  }
}

const outPath = resolve(import.meta.dirname, "../src/diagnostics/expected-pixels.ts");
const lines = [
  "// Generated by apps/web/scripts/generate-diagnostics.mjs from the engine CPU oracle.",
  "// Re-run: node apps/web/scripts/generate-diagnostics.mjs",
  "",
  "export const EXPECTED_PNGS: Readonly<Record<string, string>> = {",
  ...Object.entries(entries).map(([id, b64]) => `  ${JSON.stringify(id)}: ${JSON.stringify(b64)},`),
  "};",
  "",
];
writeFileSync(outPath, lines.join("\n"));
console.log(
  `Wrote ${Object.keys(entries).length} expected diagnostic PNGs to ${outPath} (${lines.join("\n").length} bytes).`,
);
